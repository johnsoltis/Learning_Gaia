hdf5_filelist = np.loadtxt('YOUR PATH/hdf5_filelist.txt', dtype = str)

feature_names = ['pml','pmb']#['ra', 'dec', 'parallax', 'pmra', 'pmdec', 'phot_g_mean_mag', 'phot_bp_mean_mag', 'phot_rp_mean_mag', 'radial_velocity']#list(preprocess['main_train'].keys())
dim = len(feature_names)
